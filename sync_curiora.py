"""Copy a content-pinned Curiora source distribution; no network or build tools.

Run from any directory: python sync_curiora.py [--source PATH] [--check]
Only the generated static/curiora files and voice partial are managed here.
"""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent


def snapshot(source):
    descriptor = json.loads((source/'distribution.json').read_text())
    expected = ['css/controls.css', 'js/liquid.js', 'js/voice-control.js']
    if descriptor['schema'] != 1 or descriptor['files'] != expected:
        raise ValueError('Unsupported Curiora distribution layout')
    outputs = {f'static/curiora/{Path(name).name}': (source/name).read_bytes() for name in expected}
    voice = (source/'js/voice-control.js').read_text()
    paths = json.loads(re.search(r'export const VOICE_PATHS = (\[.*?\]);', voice).group(1))
    stroke = re.search(r'export const VOICE_STROKE = ([\d.]+);', voice).group(1)
    partial = '{# Generated by sync_curiora.py from Curiora voice-control.js; do not edit. #}\n'
    partial += f'<g class="curiora-voice-wave" stroke-width="{stroke}">\n'
    partial += ''.join(f'  <path d="{html.escape(path, quote=True)}" />\n' for path in paths)
    partial += '</g>\n'
    outputs['templates/components/curiora_voice.html'] = partial.encode()
    hashes = {name: hashlib.sha256(data).hexdigest() for name, data in outputs.items()}
    digest = hashlib.sha256(json.dumps({'version': descriptor['version'], 'files': hashes}, sort_keys=True).encode()).hexdigest()
    metadata = {'schema': 1, 'version': descriptor['version'], 'snapshot_sha256': digest,
                'source_repository': 'https://github.com/Curiora-intelligence/Curiora-Design-System',
                'source_base_revision': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=source, text=True).strip(),
                'source_files_uncommitted': bool(subprocess.check_output(['git','status','--porcelain','--',*expected,'distribution.json'], cwd=source, text=True).strip()),
                'files': hashes}
    return outputs, metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT.parent/'Curiora-Design-System')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs, metadata = snapshot(args.source)
    manifest = ROOT/'static/curiora/snapshot.json'
    if args.check:
        failures = [name for name, data in outputs.items() if not (ROOT/name).exists() or (ROOT/name).read_bytes() != data]
        existing = json.loads(manifest.read_text()) if manifest.exists() else {}
        if existing.get('snapshot_sha256') != metadata['snapshot_sha256']:
            failures.append('static/curiora/snapshot.json')
        if failures:
            raise SystemExit('Snapshot differs: '+', '.join(failures))
        print('Curiora snapshot verified: '+metadata['snapshot_sha256'])
        return
    for name, data in outputs.items():
        destination = ROOT/name
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
    manifest.write_text(json.dumps(metadata, indent=2)+'\n')
    print('Curiora '+metadata['version']+' snapshot: '+metadata['snapshot_sha256'])


if __name__ == '__main__':
    main()
